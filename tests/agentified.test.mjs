  /**
   * The read action returns the right zone and price at every band boundary, and
   * refuses what the site cannot do, without changing anything. Arguments the schema
   * forbids never reach the site: the runtime rejects them as invalid arguments.
   */
  static async testGetTarifBandsAndRefusals() {
    const loaded = await AgentifiedSiteTest.load();
    const registry = await AgentifiedSiteTest.registry();
    const ctx = AgentifiedSiteTest.context(loaded, registry, new ScriptedModel([]), AgentifiedSiteTest.approve);
    const entry = await AgentifiedSiteTest.tool(loaded, ctx, READ_ACTION);
    const before = await AgentifiedSiteTest.readState(registry);
    AgentifiedSiteTest.clearFocus();
    // Band boundaries, worked out by hand from data/tarif.json.
    const accepted = [
      [{ jarakKm: 0 }, 8000, "dekat"],
      [{ jarakKm: 3 }, 8000, "dekat"],
      [{ jarakKm: 3.1 }, 12000, "sedang"],
      [{ jarakKm: 7 }, 12000, "sedang"],
      [{ jarakKm: 7.1 }, 18000, "jauh"],
      [{ jarakKm: 15 }, 18000, "jauh"],
      [{ jarakKm: 5, jam: "18:00" }, 12000, "sedang"],
      [{ jarakKm: 5, jam: "07:00" }, 12000, "sedang"],
    ];
    for (const [args, ongkir, band] of accepted) {
      const receipt = await dispatchToolCall(ctx, entry, args, null, []);
      assert.equal(receipt.status, "succeeded");
      assert.equal(receipt.result.ok, true, receipt.result.reason);
      assert.equal(receipt.result.ongkir, ongkir, `Wrong price for ${JSON.stringify(args)}.`);
      assert.equal(receipt.result.band.id, band, `Wrong zone for ${JSON.stringify(args)}.`);
    }
    // The read moves no focus and changes nothing on the page.
    assert.deepEqual(AgentifiedSiteTest.focusedIds(), [], `website_${READ_ACTION} moved focus.`);
    assert.deepEqual(await AgentifiedSiteTest.readState(registry), before);
    // Site-level refusals: the site's own reason, nothing changed.
    const refused = [
      [{ jarakKm: 5, jam: "12:00" }, /penuh/],
      [{ jarakKm: 5, jam: "19:00" }, /07:00–18:00/],
      [{ jarakKm: 5, jam: "pagi" }, /07:00–18:00/],
    ];
    for (const [args, reason] of refused) {
      const receipt = await dispatchToolCall(ctx, entry, args, null, []);
      assert.equal(receipt.status, "succeeded");
      assert.equal(receipt.result.ok, false, `The site accepts ${JSON.stringify(args)}.`);
      assert.match(receipt.result.reason, reason);
    }
    assert.deepEqual(await AgentifiedSiteTest.readState(registry), before);
    // Schema-level refusals: out of range and negative distances never reach the site.
    await assert.rejects(dispatchToolCall(ctx, entry, { jarakKm: 15.1 }, null, []), /Invalid arguments/);
    await assert.rejects(dispatchToolCall(ctx, entry, { jarakKm: 20 }, null, []), /Invalid arguments/);
    await assert.rejects(dispatchToolCall(ctx, entry, { jarakKm: -1 }, null, []), /Invalid arguments/);
    assert.deepEqual(await AgentifiedSiteTest.readState(registry), before);
  }

